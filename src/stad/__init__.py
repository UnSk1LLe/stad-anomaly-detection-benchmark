"""STAD — объективное сравнение архитектур детекции аномалий трафика.

Пакет построен вокруг одного разделения, которого нет в литературе:

    энкодер (пространственно-временное представление)
        × голова (механизм anomaly score)
        × протокол (метрики и контроли)

Литература смешивает эти три оси, из-за чего невозможно понять, чем
вызван заявленный выигрыш. Разделив их и выровняв бюджет параметров,
можно измерить вклад каждой.

Точки входа:

* ``stad.data`` — единый контракт данных, FT-AED и синтетический коридор;
* ``stad.encoders`` / ``stad.heads`` — две оси сравнения;
* ``stad.baselines`` — доменные бейзлайны и протокольные контроли;
* ``stad.metrics`` — event-level метрики, PR, статистика;
* ``stad.registry`` — какие конфигурации сравниваются и зачем;
* ``stad.runner`` — прогон сетки;
* ``stad.viz`` — фигуры отчёта.
"""
